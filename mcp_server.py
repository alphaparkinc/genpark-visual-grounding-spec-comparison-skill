import json, sys
from client import VisualGroundingSpecComparisonClient

def handle_mcp_request(payload):
    method = payload.get("method")
    req_id = payload.get("id", 1)
    if method == "initialize":
        return {"jsonrpc": "2.0", "id": req_id, "result": {"protocolVersion": "2024-11-05", "serverInfo": {"name": "visual-grounding-spec", "version": "1.0.0"}}}
    elif method == "tools/list":
        return {"jsonrpc": "2.0", "id": req_id, "result": {"tools": [{"name": "compare_visual_specs", "description": "Compares hardware visual specifications, DoF dimensions, and form factors."}]}}
    elif method == "tools/call":
        client = VisualGroundingSpecComparisonClient()
        res = client.compare_visual_specs()
        return {"jsonrpc": "2.0", "id": req_id, "result": {"content": [{"type": "text", "text": json.dumps(res, indent=2)}]}}
    return {"jsonrpc": "2.0", "id": req_id, "result": {"status": "ACTIVE"}}

if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "--test":
        print(json.dumps(handle_mcp_request({"method": "tools/list"})))
    else:
        client = VisualGroundingSpecComparisonClient()
        print(json.dumps(client.compare_visual_specs(), indent=2))
